import { prisma } from "@/lib/prisma";

// Every user-scoped table, dumped flat. §16: "Never lose data... I want to
// be able to walk away from this app with my content." Deliberately a flat
// object of arrays (one key per table) rather than trying to reconstruct
// nested relations — it's a backup, not an import format; a restore would
// go table-by-table against the same schema.
export async function exportAllData(userId: string) {
  const [
    subjects,
    units,
    topics,
    subtopics,
    learningObjectives,
    cards,
    cardMedia,
    reviews,
    cardScheduling,
    studySessions,
    dailyPlans,
    weeklyReviews,
    formulaEntries,
    assumedKnowledge,
    documents,
    pastPapers,
    paperAttempts,
    attemptResponses,
    aiConversations,
    aiMessages,
    teachBackSessions,
    timetableBlocks,
    calendarEvents,
  ] = await Promise.all([
    prisma.subject.findMany({ where: { userId } }),
    prisma.unit.findMany({ where: { userId } }),
    prisma.topic.findMany({ where: { userId } }),
    prisma.subtopic.findMany({ where: { userId } }),
    prisma.learningObjective.findMany({ where: { userId } }),
    prisma.card.findMany({ where: { userId } }),
    prisma.cardMedia.findMany({ where: { userId } }),
    prisma.review.findMany({ where: { userId } }),
    prisma.cardScheduling.findMany({ where: { userId } }),
    prisma.studySession.findMany({ where: { userId } }),
    prisma.dailyPlan.findMany({ where: { userId } }),
    prisma.weeklyReview.findMany({ where: { userId } }),
    prisma.formulaEntry.findMany({ where: { userId } }),
    prisma.assumedKnowledge.findMany({ where: { userId } }),
    prisma.document.findMany({ where: { userId } }),
    prisma.pastPaper.findMany({ where: { userId } }),
    prisma.paperAttempt.findMany({ where: { userId } }),
    prisma.attemptResponse.findMany({ where: { userId } }),
    prisma.aiConversation.findMany({ where: { userId } }),
    prisma.aiMessage.findMany({ where: { userId } }),
    prisma.teachBackSession.findMany({ where: { userId } }),
    prisma.timetableBlock.findMany({ where: { userId } }),
    prisma.calendarEvent.findMany({ where: { userId } }),
  ]);

  return {
    exportedAt: new Date().toISOString(),
    userId,
    subjects,
    units,
    topics,
    subtopics,
    learningObjectives,
    cards,
    cardMedia,
    reviews,
    cardScheduling,
    studySessions,
    dailyPlans,
    weeklyReviews,
    formulaEntries,
    assumedKnowledge,
    documents,
    pastPapers,
    paperAttempts,
    attemptResponses,
    aiConversations,
    aiMessages,
    teachBackSessions,
    timetableBlocks,
    calendarEvents,
  };
}
